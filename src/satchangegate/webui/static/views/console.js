import { api, el, chip, commandLine, spinner, setStatus } from "../app.js";

export const title = "Console";
export const group = "Lab";

/* Every operation the project has, as a form built from the request schema the
   server validates against. The command shown is not assembled here: it comes
   back from the server, rendered from the same validated request a run would
   use. Assembling it in JavaScript would make it a caption again. */

let state = { operation: null, params: {}, running: false };

export async function render(mount, ctx) {
  const { operations } = await api.get("/api/operations");
  const caps = ctx.capabilities || { operations: [] };
  const availability = new Map((caps.operations || []).map((o) => [o.name, o]));

  mount.append(el("header", {},
    el("h1", {}, "Command console"),
    el("p", { class: "lede" },
      "Every capability the project exposes, over the same service layer the CLI " +
      "uses. The command below each form is generated by the server from the " +
      "validated request, so what you copy is what would run.")));

  const layout = el("div", { class: "grid cols-2" });
  const list = el("div", { class: "card" });
  const panel = el("div", { class: "card" });
  layout.append(list, panel);
  mount.append(layout);

  list.append(el("h3", {}, "Operations"));
  const rows = el("div", { class: "grid" });
  for (const op of operations) {
    const avail = availability.get(op.name) || {};
    const blocked = avail.available === false;
    rows.append(el("button", {
      class: "btn",
      style: "text-align:left; display:grid; gap:4px;",
      onClick: () => select(op, panel, avail),
    },
      el("span", {},
        el("code", {}, op.name), " ",
        op.spends_money ? chip("spends", "warn") : "",
        blocked ? chip("blocked", "stop") : ""),
      el("span", { class: "dim", style: "font-size:12px" }, op.summary)));
  }
  list.append(rows);

  panel.append(el("p", { class: "dim" }, "Pick an operation to build a request."));
}

function select(op, panel, avail) {
  state = { operation: op, params: {}, running: false };
  panel.replaceChildren();
  panel.append(el("h3", {}, el("code", {}, op.name)));
  panel.append(el("p", { class: "dim" }, op.summary));

  if (avail.available === false) {
    panel.append(el("div", { class: "notice stop" },
      el("strong", {}, "Not runnable here. "),
      `Blocked by: ${(avail.blocked_by || []).join(", ")}.`));
  }

  const schema = op.schema || {};
  const props = schema.properties || {};
  const form = el("div", { class: "grid" });

  for (const [name, spec] of Object.entries(props)) {
    if (name === "root" || name === "out") continue; // locations, not parameters
    form.append(field(name, spec, () => refresh(panel, op)));
  }
  panel.append(form);

  const preview = el("div", { id: "cmd-preview" });
  panel.append(preview);
  refresh(panel, op);
}

function field(name, spec, onChange) {
  const label = el("label", { class: "field" }, el("span", {}, name));
  const enumValues = spec.enum || spec.anyOf?.find((a) => a.enum)?.enum;
  let input;

  if (spec.type === "boolean") {
    input = el("input", { type: "checkbox" });
    input.style.width = "auto";
    input.addEventListener("change", () => {
      setParam(name, input.checked || undefined);
      onChange();
    });
  } else if (enumValues) {
    input = el("select", {}, el("option", { value: "" }, "(default)"),
      ...enumValues.filter((v) => v !== null).map((v) => el("option", { value: v }, String(v))));
    input.addEventListener("change", () => {
      setParam(name, input.value || undefined);
      onChange();
    });
  } else {
    const numeric = spec.type === "number" || spec.type === "integer"
      || spec.anyOf?.some((a) => a.type === "number" || a.type === "integer");
    input = el("input", { type: numeric ? "number" : "text", step: "any",
      placeholder: describeDefault(spec) });
    input.addEventListener("input", () => {
      const raw = input.value.trim();
      setParam(name, raw === "" ? undefined : (numeric ? Number(raw) : raw));
      onChange();
    });
  }
  label.append(input);
  if (spec.description) label.append(el("span", { class: "hint" }, spec.description));
  return label;
}

function describeDefault(spec) {
  if (spec.default === undefined || spec.default === null) return "";
  return `default ${JSON.stringify(spec.default)}`;
}

function setParam(name, value) {
  if (value === undefined) delete state.params[name];
  else state.params[name] = value;
}

async function refresh(panel, op) {
  const slot = panel.querySelector("#cmd-preview");
  if (!slot) return;
  slot.replaceChildren(spinner("validating…"));
  try {
    const res = await api.post("/api/commands/preview", {
      operation: op.name,
      params: state.params,
    });
    slot.replaceChildren(
      commandLine(res.command),
      el("details", {},
        el("summary", { class: "dim" }, "normalised request"),
        el("pre", { class: "mono", style: "overflow-x:auto; font-size:12px" },
          JSON.stringify(res.normalised, null, 2))),
      el("p", { class: "dim" },
        "Execution from the browser arrives with the job runner and the " +
        "reservation ledger. Until then this validates the request and hands " +
        "you the command."),
    );
    setStatus(undefined, `${op.name}: request valid`);
  } catch (err) {
    slot.replaceChildren(el("div", { class: "notice stop" },
      el("strong", {}, "Invalid request. "), String(err.message || err)));
    setStatus(undefined, `${op.name}: request invalid`);
  }
}
